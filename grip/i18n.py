from __future__ import annotations

import locale

LANGUAGES = ("auto", "zh_CN", "en")


def resolve_language(language: str, system_locale: str | None = None) -> str:
    if language in ("zh_CN", "en"):
        return language
    if system_locale is None:
        try:
            system_locale = locale.getlocale()[0] or "en"
        except (ValueError, TypeError):
            system_locale = "en"
    return "zh_CN" if system_locale.lower().startswith("zh") else "en"


